#!/usr/bin/env node
/**
 * Extracts default content from app page files (hajj-umrah.tsx, seerah.tsx, companions.tsx)
 * and generates admin-panel/src/data/app-defaults.ts in CMS format.
 *
 * Run: node admin-panel/scripts/generate-defaults.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../..');

function readFile(relPath) {
  return fs.readFileSync(path.join(ROOT, relPath), 'utf-8');
}

/**
 * Extract a top-level const array/object from a TypeScript source string.
 * Returns the raw JS text for that array (including brackets).
 */
function extractArrayText(src, varName) {
  // Find `const VARNAME: SomeType[] = [`  or `const VARNAME = [`
  const regex = new RegExp(`const\\s+${varName}[^=]*=\\s*\\[`);
  const match = src.match(regex);
  if (!match) throw new Error(`Cannot find ${varName} in source`);

  const startIdx = src.indexOf(match[0]) + match[0].length - 1;
  let depth = 1;
  let pos = startIdx + 1;

  while (pos < src.length && depth > 0) {
    const ch = src[pos];
    if (ch === '[') depth++;
    else if (ch === ']') depth--;
    // Skip string literals
    else if (ch === "'" || ch === '"' || ch === '`') {
      const quote = ch;
      pos++;
      while (pos < src.length && src[pos] !== quote) {
        if (src[pos] === '\\') pos++; // skip escaped char
        pos++;
      }
    }
    pos++;
  }

  return src.substring(startIdx, pos);
}

/**
 * Evaluate a JS array expression string safely.
 */
function evalArray(text) {
  // The data is pure literals — safe to eval
  return eval('(' + text + ')');
}

// ─── Read sources ──────────────────────────────────────────────────
const hajjSrc = readFile('app/hajj-umrah.tsx');
const seerahSrc = readFile('app/seerah.tsx');
const companionsSrc = readFile('app/companions.tsx');

// ─── Extract arrays ────────────────────────────────────────────────
const UMRAH_SECTIONS = evalArray(extractArrayText(hajjSrc, 'UMRAH_SECTIONS'));
const HAJJ_SECTIONS = evalArray(extractArrayText(hajjSrc, 'HAJJ_SECTIONS'));
const DUAS_BY_RITUAL = evalArray(extractArrayText(hajjSrc, 'DUAS_BY_RITUAL'));
const SEERAH_SECTIONS = evalArray(extractArrayText(seerahSrc, 'SEERAH_SECTIONS'));
const COMPANIONS = evalArray(extractArrayText(companionsSrc, 'COMPANIONS'));

// ─── Convert to CMS format ─────────────────────────────────────────

function convertRitualSection(s) {
  return {
    title: s.title,
    titleTranslations: { en: s.titleEn || '' },
    icon: s.icon,
    description: s.description,
    steps: s.steps.map(st => ({ text: st.text })),
    duas: s.duas.map(d => ({ arabic: d.arabic, note: d.note || '' })),
  };
}

function convertDuaGroup(g) {
  return {
    title: g.title,
    icon: g.icon,
    duas: g.duas.map(d => ({
      arabic: d.arabic,
      reference: d.reference || '',
      occasion: d.occasion,
    })),
  };
}

function convertSeerahSection(s) {
  return {
    title: s.title,
    titleEn: s.titleEn || '',
    icon: s.icon,
    paragraphs: s.paragraphs,
  };
}

function convertCompanion(c) {
  return {
    id: c.id,
    nameAr: c.nameAr,
    nameEn: c.nameEn,
    category: c.category,
    brief: c.brief,
    story: c.story,
    virtues: c.virtues,
  };
}

const cmsHajjUmrah = {
  umrahSections: UMRAH_SECTIONS.map(convertRitualSection),
  hajjSections: HAJJ_SECTIONS.map(convertRitualSection),
  duasByRitual: DUAS_BY_RITUAL.map(convertDuaGroup),
};

const cmsSeerah = {
  sections: SEERAH_SECTIONS.map(convertSeerahSection),
};

const cmsCompanions = {
  companions: COMPANIONS.map(convertCompanion),
  categories: [
    { key: 'ashara', title: 'العشرة المبشرون بالجنة', icon: 'star-crescent' },
    { key: 'muhajirun', title: 'المهاجرون', icon: 'road-variant' },
    { key: 'ansar', title: 'الأنصار', icon: 'home-heart' },
    { key: 'mothers', title: 'أمهات المؤمنين', icon: 'heart-multiple' },
  ],
};

// ─── Generate TypeScript output ────────────────────────────────────

function toTS(obj, indent = 2) {
  return JSON.stringify(obj, null, indent)
    // Unescape unicode so Arabic is readable
    .replace(/\\u[\da-fA-F]{4}/g, match =>
      String.fromCharCode(parseInt(match.replace('\\u', ''), 16))
    );
}

const output = `/**
 * AUTO-GENERATED — do not edit manually.
 * Generated by: admin-panel/scripts/generate-defaults.js
 * Source: app/hajj-umrah.tsx, app/seerah.tsx, app/companions.tsx
 *
 * Contains the app's hardcoded default content converted to CMS format.
 * Used by ContentManager to pre-populate empty categories and support "Import Defaults".
 */

// ─── Types (matching ContentManager.tsx) ────────────────────────────

interface DefaultRitualSection {
  title: string;
  titleTranslations?: Record<string, string>;
  icon: string;
  description: string;
  steps: { text: string }[];
  duas: { arabic: string; note?: string }[];
}

interface DefaultDuaGroup {
  title: string;
  icon: string;
  duas: { arabic: string; reference?: string; occasion: string }[];
}

interface DefaultHajjUmrahContent {
  umrahSections: DefaultRitualSection[];
  hajjSections: DefaultRitualSection[];
  duasByRitual: DefaultDuaGroup[];
}

interface DefaultSeerahSection {
  title: string;
  titleEn: string;
  icon: string;
  paragraphs: string[];
}

interface DefaultSeerahContent {
  sections: DefaultSeerahSection[];
}

interface DefaultCompanion {
  id: string;
  nameAr: string;
  nameEn: string;
  category: string;
  brief: string;
  story: string[];
  virtues: string[];
}

interface DefaultCompanionsContent {
  companions: DefaultCompanion[];
  categories: { key: string; title: string; icon: string }[];
}

// ─── Hajj & Umrah Default Content ───────────────────────────────────

export function getDefaultHajjUmrahContent(): DefaultHajjUmrahContent {
  return ${toTS(cmsHajjUmrah)};
}

// ─── Seerah Default Content ─────────────────────────────────────────

export function getDefaultSeerahContent(): DefaultSeerahContent {
  return ${toTS(cmsSeerah)};
}

// ─── Companions Default Content ─────────────────────────────────────

export function getDefaultCompanionsContent(): DefaultCompanionsContent {
  return ${toTS(cmsCompanions)};
}
`;

const outPath = path.join(__dirname, '../src/data/app-defaults.ts');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, output, 'utf-8');

console.log(`✅ Generated ${outPath}`);
console.log(`   Hajj sections: ${HAJJ_SECTIONS.length}`);
console.log(`   Umrah sections: ${UMRAH_SECTIONS.length}`);
console.log(`   Dua groups: ${DUAS_BY_RITUAL.length}`);
console.log(`   Seerah sections: ${SEERAH_SECTIONS.length}`);
console.log(`   Companions: ${COMPANIONS.length}`);
