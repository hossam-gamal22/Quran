const _filenameSet = new Set(AZKAR_FILENAMES);

/** Check whether audio exists for a given azkar filename. */
export function hasAzkarAudio(filename: string | null | undefined): boolean {
  if (!filename) return false;
  const mp3Key = filename.replace(/\.m4a$/, ".mp3");
  return _filenameSet.has(mp3Key) || _filenameSet.has(filename);
}

/** Resolve a filename (possibly .m4a) to its canonical .mp3 key in the list, or null. */
export function resolveAzkarFilename(filename: string | null | undefined): string | null {
  if (!filename) return null;
  const mp3Key = filename.replace(/\.m4a$/, ".mp3");
  if (_filenameSet.has(mp3Key)) return mp3Key;
  if (_filenameSet.has(filename)) return filename;
  return null;
}

/** GitHub raw base URL for azkar audio files. */
export const GITHUB_BASE =
  'https://raw.githubusercontent.com/hossam-gamal22/Quran/main/assets/sounds/azkar_authentic/';

/**
 * Returns a GitHub raw URL for the given azkar audio filename, or null if unknown.
 * Handles legacy .m4a → .mp3 conversion.
 */
export const getAzkarAudioSource = (filename: string | null | undefined): string | null => {
  const resolved = resolveAzkarFilename(filename);
  if (!resolved) return null;
  return `${GITHUB_BASE}${encodeURIComponent(resolved)}`;
};
