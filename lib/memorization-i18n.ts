const dicts: Partial<Record<Language, Dict>> = { ar, en };

export function mt(key: string, params?: Record<string, string | number>): string {
  const lang = getLanguage();
  const dict = dicts[lang] ?? en;
  let val = dict[key] ?? en[key] ?? key;
  if (params) {
    for (const p of Object.keys(params)) {
      const raw = params[p];
      let formatted = String(raw);
      val = val.replace(new RegExp(`\\{${p}\\}`, 'g'), formatted);
    }
  }
  return val;
}
