/**
 * Notification Channels — إدارة قنوات الإشعارات
 *
 * ONE CHANNEL PER SOUND FILE — Android caches channel sounds at creation time
 * and they are immutable afterward. Instead of deleting/recreating channels
 * when the user changes their sound preference, we create ALL possible
 * channels upfront at app startup and simply switch which channelId we use
 * when scheduling notifications.
 *
 * Sound name rules:
 * - Filename only, lowercase, no path prefix
 * - Android raw resources: WITHOUT .mp3 extension
 * - iOS: WITH .mp3 extension
 */

